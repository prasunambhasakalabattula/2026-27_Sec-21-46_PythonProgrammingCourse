# Operator Precedence and Associativity
#example of operator precedence and associativity
x = 10
y = 5
# Using parentheses to change the order of operations
# Without parentheses: 10 + 10 = 20
result1 = x + y * 2  
# with paranthesis: 15 * 2 =30 
result2 = (x + y) * 2
print(f"Without parentheses: {result1}")
print(f"With parentheses: {result2}")